"""Honest subscriptions on PayPal Subscriptions: TrustLayer Plus and a kit any seller can use.

Research (BestMoney 2026, Self Financial 2026): about 7 in 10 US adults have been charged after forgetting a free
trial, and 20+ US states now require click-to-cancel. Forgotten-trial charges also come back as chargebacks, which hurts
the seller's dispute ratio. So every offering, the marketplace's own Plus or a seller's, follows the same rules:

- Terms review before launch: an LLM flags dark patterns in the seller's text and suggests a clearer version. The legally
  important disclosure (price, renewal, trial, how to cancel) is generated by code, and code blocks the worst phrases.
- A real free trial (TRIAL billing cycle on an ACTIVE PayPal plan). Every subscription is verified with PayPal
  (GET /v1/billing/subscriptions/{id}, matching plan, ACTIVE/APPROVED) before anything is granted.
- Before the first charge: an AI-written reminder that honestly says whether it was used. Facts come from code.
- Cancel in one confirmation, always available. A pause may be offered only if the subscriber got real value.
- Sellers see which trial subscribers are about to be charged without ever using it (future chargebacks).
- Lifecycle state stays in sync with PayPal via BILLING.SUBSCRIPTION.* / PAYMENT.SALE.COMPLETED webhooks.
"""
import json
import re
import time
import uuid

from . import config, db, ledger, llm, orders, paypal

PLUS_ID = "plus"
REMIND_BEFORE_DAYS = 2
PLUS = {"id": PLUS_ID, "seller_id": None, "name": "TrustLayer Plus", "price": 4.99, "trial_days": 7,
        "description": "Extra protection for marketplace payments.",
        "benefits": ["24-hour cooling-off on any payment you choose", "Trusted-contact alerts on every paused payment",
                     "Priority resolution with the seller's assistant"]}

# Phrases that make a subscription a trap. Code blocks these regardless of what the LLM says.
BLOCKED_TERMS = [
    (r"\b(?:call|phone|email|write to)\b.{0,30}\bto cancel\b|\bcancel(?:lation)?s?\b.{0,30}\bby (?:phone|mail|calling)\b",
     "Cancelling must not require a call, email or letter"),
    (r"\bcancell?ation fee\b|\bfee to cancel\b|\bearly termination fee\b", "No cancellation or early-termination fees"),
    (r"\bminimum (?:term|commitment|of \d+ months?)\b|\b\d+[- ]month (?:minimum|commitment|lock[- ]?in)\b",
     "No minimum terms on a monthly plan"),
    (r"\bno cancell?ations?\b|\bcannot be cancell?ed\b|\bnon[- ]cancell?able\b", "Members must be able to cancel"),
]


def disclosure(off: dict) -> str:
    """The clear-terms statement every offering shows. Written by code, never by the model."""
    trial = f" after a {off['trial_days']}-day free trial" if off["trial_days"] else ""
    return (f"${off['price']:.2f} per month{trial}, renews monthly until you cancel. You'll get a reminder "
            f"{REMIND_BEFORE_DAYS} days before the first charge. Cancel any time in one confirmation.")


# ---------------- offerings ----------------

def _kv(key: str) -> str | None:
    row = db.one("SELECT v FROM kv WHERE k = ?", (key,))
    return row["v"] if row else None


def _set_kv(key: str, value: str) -> None:
    db.run("INSERT INTO kv (k, v) VALUES (?, ?) ON CONFLICT(k) DO UPDATE SET v = excluded.v", (key, value))


def seed_offerings() -> None:
    now = time.time()
    rows = [PLUS, {"id": "maya-film-club", "seller_id": "maya", "name": "Film Roll Club", "price": 12.0, "trial_days": 14,
                   "description": "Two rolls of fresh 35mm film every month, hand-picked, plus a 10% discount on cameras.",
                   "benefits": ["2 rolls of 35mm film a month", "10% off any camera in the shop", "Free light-seal check"]}]
    for o in rows:
        db.run("INSERT OR IGNORE INTO offerings (id, seller_id, name, description, price, trial_days, benefits_json, "
               "status, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)",
               (o["id"], o["seller_id"], o["name"], o["description"], o["price"], o["trial_days"],
                json.dumps(o["benefits"]), "ACTIVE", now, now))


def offering(off_id: str) -> dict:
    if not db.one("SELECT 1 AS x FROM offerings WHERE id = ?", (PLUS_ID,)):
        seed_offerings()
    o = db.one("SELECT * FROM offerings WHERE id = ?", (off_id,))
    if not o:
        raise orders.OrderError("offering not found", 404)
    o["benefits"] = db.loads(o.pop("benefits_json"), [])
    o["review"] = db.loads(o.pop("review_json"), None)
    o["disclosure"] = disclosure(o)
    return o


def plan_id_for(off: dict) -> str:
    """Create (once) the PayPal catalog product + ACTIVE billing plan for an offering. Ids are cached in kv."""
    if off["id"] == PLUS_ID and config.PLUS_PLAN_ID:
        return config.PLUS_PLAN_ID  # env pin survives hosts with ephemeral disks
    cached = _kv(f"plan:{off['id']}") or (_kv("plus_plan_id") if off["id"] == PLUS_ID else None)
    if cached:
        return cached
    ref = f"{(config.PAYPAL_CLIENT_ID or 'local')[-8:]}-{off['id']}"
    product = paypal.create_product(off["name"], off["description"][:120] or off["name"], ref)
    plan = paypal.create_plan(product["id"], off["name"], float(off["price"]), int(off["trial_days"]), ref)
    _set_kv(f"plan:{off['id']}", plan["id"])
    ledger.append("subscription.plan_created", {"offering_id": off["id"], "product_id": product["id"],
                                                "plan_id": plan["id"], "price": off["price"],
                                                "trial_days": off["trial_days"]}, seller_id=off["seller_id"])
    return plan["id"]


def public_offering(off: dict) -> dict:
    out = {k: off[k] for k in ("id", "seller_id", "name", "description", "price", "trial_days", "benefits", "disclosure",
                               "status")}
    if off["seller_id"]:
        s = db.one("SELECT name, handle FROM sellers WHERE id = ?", (off["seller_id"],))
        out["seller"] = s
    try:
        out["plan_id"] = plan_id_for(off)
    except paypal.PayPalError as e:
        out["plan_id"], out["error"] = None, str(e)
    return out


def list_offerings(seller_id: str | None = None) -> list[dict]:
    offering(PLUS_ID)  # ensures seed rows exist
    if seller_id:
        rows = db.all("SELECT id FROM offerings WHERE seller_id = ? AND status = 'ACTIVE' ORDER BY created_at", (seller_id,))
    else:
        rows = db.all("SELECT id FROM offerings WHERE status = 'ACTIVE' ORDER BY (id = 'plus') DESC, created_at")
    return [public_offering(offering(r["id"])) for r in rows]


REVIEW_SYSTEM = """You review the terms a small online seller wrote for a monthly subscription, before it goes live.
Flag anything that could trap or confuse a customer under US auto-renewal and click-to-cancel rules: unclear price or
billing frequency, unclear when the trial ends and charging starts, hidden fees, cancellation hurdles (calls, emails,
minimum terms), pre-checked add-ons, or promises the seller may not keep. Be practical and brief; do not invent problems.
Return JSON only:
{"issues": [{"severity": "high"|"medium"|"low", "problem": "short", "fix": "short"}],
 "improved_description": "a clearer, friendly 1-2 sentence description that keeps the seller's offer",
 "verdict": "ready"|"fix_first"}"""


def review_terms(name: str, description: str, price: float, trial_days: int) -> dict:
    draft = {"name": name, "description": description, "price": price, "trial_days": trial_days}
    blocking = [msg for rx, msg in BLOCKED_TERMS if re.search(rx, f"{name} {description}", re.I)]
    out = {"blocking": blocking, "disclosure": disclosure(draft), "issues": [], "improved_description": description,
           "verdict": "fix_first" if blocking else "ready", "model": None}
    try:
        prompt = {**draft, "not_allowed_on_this_platform": blocking or [msg for _, msg in BLOCKED_TERMS],
                  "always_shown_next_to_the_description": out["disclosure"],
                  "rule": ("improved_description must remove every not-allowed term, not restate it. Price, renewal, "
                           "trial end and how to cancel are already covered by the disclosure that is always shown; do "
                           "not flag those as missing. Focus on the seller's own wording.")}
        res = llm.complete_json(REVIEW_SYSTEM, json.dumps(prompt), temperature=0.1)
        d = res["data"] if isinstance(res["data"], dict) else {}
        out["issues"] = [i for i in (d.get("issues") or []) if isinstance(i, dict) and i.get("problem")][:6]
        improved = (d.get("improved_description") or description).strip()
        # the model's rewrite must itself pass the hard rules, or we don't suggest it
        if any(re.search(rx, improved, re.I) for rx, _ in BLOCKED_TERMS):
            improved = description
        out["improved_description"] = improved
        out["model"] = res["model"]
        if d.get("verdict") == "fix_first" and any(i.get("severity") == "high" for i in out["issues"]):
            out["verdict"] = "fix_first"
    except llm.LLMUnavailable:
        out["issues"] = [{"severity": "low", "problem": "AI review unavailable right now", "fix": "Rules-based checks still applied"}]
    if blocking:  # code has the final say on the hard rules
        out["verdict"] = "fix_first"
    return out


def create_offering(seller_id: str, name: str, description: str, price: float, trial_days: int) -> dict:
    if not db.one("SELECT 1 AS x FROM sellers WHERE id = ?", (seller_id,)):
        raise orders.OrderError("seller not found", 404)
    if not (1 <= price <= 500) or not (0 <= trial_days <= 30):
        raise orders.OrderError("price must be $1-$500 and the trial 0-30 days")
    review = review_terms(name, description, price, trial_days)
    if review["blocking"]:
        raise orders.OrderError("These terms can't go live: " + "; ".join(review["blocking"]), 422)
    oid = f"{seller_id}-{re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')[:24]}-{uuid.uuid4().hex[:4]}"
    now = time.time()
    db.run("INSERT INTO offerings (id, seller_id, name, description, price, trial_days, benefits_json, review_json, "
           "status, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
           (oid, seller_id, name.strip(), description.strip(), round(price, 2), int(trial_days), "[]", json.dumps(review),
            "ACTIVE", now, now))
    off = offering(oid)
    plan_id_for(off)
    ledger.append("subscription.offering_created", {"offering_id": oid, "name": name, "price": price,
                                                    "trial_days": trial_days, "review_verdict": review["verdict"],
                                                    "issues": len(review["issues"])}, seller_id=seller_id)
    return public_offering(offering(oid))


# ---------------- subscriptions ----------------

def _now(sub: dict) -> float:
    return time.time() + (sub.get("clock_offset") or 0)


def _plus_usage() -> dict:
    """What a Plus member actually got out of it (single demo buyer: all marketplace orders)."""
    rows = db.all("SELECT * FROM orders")
    paused = [o for o in rows if (db.loads(o["risk_json"], {}) or {}).get("verdict") == "PAUSE"]
    voided = sum(o["amount"] for o in rows if o["status"] == "CANCELLED")
    released = sum(max(0, o["amount"] - (o["captured_amount"] or 0)) for o in rows if o["captured_amount"])
    resolved = db.one("SELECT COUNT(*) AS n FROM issues WHERE status = 'RESOLVED'")["n"]
    return {"payments_protected": len(rows), "payments_paused": len(paused), "problems_resolved": resolved,
            "money_kept_safe": round(voided + released, 2)}


def _usage(sub: dict) -> dict:
    if (sub.get("offering_id") or PLUS_ID) == PLUS_ID:
        return _plus_usage()
    return {"deliveries_received": sub.get("uses") or 0}


def _used(usage: dict) -> bool:
    return any(v for k, v in usage.items() if k != "money_kept_safe")


def view_sub(sub: dict) -> dict:
    off = offering(sub.get("offering_id") or PLUS_ID)
    now = _now(sub)
    in_trial = sub["status"] in ("ACTIVE", "APPROVED") and now < (sub["trial_ends_at"] or 0)
    days = max(0, round(((sub["next_billing_at"] or now) - now) / 86400, 1))
    usage = _usage(sub)
    return {
        "id": sub["id"], "status": sub["status"], "in_trial": in_trial, "offering": public_offering(off),
        "trial_ends_at": sub["trial_ends_at"], "next_billing_at": sub["next_billing_at"], "price": sub["price"],
        "days_until_charge": days,
        "reminder_due": in_trial and now >= (sub["trial_ends_at"] or 0) - REMIND_BEFORE_DAYS * 86400,
        "simulated_days": round((sub.get("clock_offset") or 0) / 86400, 1),
        "reminder": db.loads(sub["reminder_json"], None), "cancel_reason": sub["cancel_reason"],
        "cancelled_at": sub["cancelled_at"], "usage": usage, "used": _used(usage),
        # a charge to someone who never used it is the classic "forgotten trial" chargeback
        "chargeback_risk": in_trial and not _used(usage) and days <= REMIND_BEFORE_DAYS + 1,
    }


def view(sub: dict | None) -> dict:
    """Plus page shape, kept for the /api/plus endpoints."""
    plus = public_offering(offering(PLUS_ID))
    return {"plan": {**plus, "plan_id": plus.get("plan_id")}, "subscription": view_sub(sub) if sub else None}


def current() -> dict | None:
    return db.one("SELECT * FROM subscriptions WHERE COALESCE(offering_id, 'plus') = 'plus' ORDER BY created_at DESC LIMIT 1")


def mine() -> list[dict]:
    return [view_sub(s) for s in db.all("SELECT * FROM subscriptions ORDER BY created_at DESC")]


def get(sub_id: str) -> dict:
    sub = db.one("SELECT * FROM subscriptions WHERE id = ?", (sub_id,))
    if not sub:
        raise orders.OrderError("subscription not found", 404)
    return sub


def _sync(sub_id: str, remote: dict) -> None:
    bi = remote.get("billing_info") or {}
    nxt = bi.get("next_billing_time")
    fields = {"status": remote.get("status"),
              "paypal_json": json.dumps({k: remote.get(k) for k in ("status", "start_time", "plan_id")})}
    if nxt:
        fields["next_billing_at"] = time.mktime(time.strptime(nxt[:19], "%Y-%m-%dT%H:%M:%S")) - time.timezone
    db.update("subscriptions", "id", sub_id, **fields)


def register(subscription_id: str, offering_id: str = PLUS_ID) -> dict:
    """Called after the buyer approves in PayPal. Never trust the browser: verify with PayPal first."""
    off = offering(offering_id)
    plan_id = plan_id_for(off)
    remote = paypal.get_subscription(subscription_id)
    if remote.get("plan_id") != plan_id:
        raise orders.OrderError("subscription is for a different plan", 400)
    if remote.get("status") not in ("ACTIVE", "APPROVED"):
        raise orders.OrderError(f"PayPal reports this subscription as {remote.get('status')}", 409)
    now = time.time()
    trial_end = now + off["trial_days"] * 86400
    if not db.one("SELECT 1 AS x FROM subscriptions WHERE id = ?", (subscription_id,)):
        db.run("INSERT INTO subscriptions (id, plan_id, status, started_at, trial_ends_at, next_billing_at, price, "
               "offering_id, seller_id, uses, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,0,?,?)",
               (subscription_id, plan_id, remote["status"], now, trial_end, trial_end, off["price"], off["id"],
                off["seller_id"], now, now))
    _sync(subscription_id, remote)
    ledger.append("subscription.started", {"subscription_id": subscription_id, "offering_id": off["id"],
                                           "status": remote["status"], "trial_days": off["trial_days"],
                                           "price": off["price"], "verified_with_paypal": True}, seller_id=off["seller_id"])
    return view_sub(get(subscription_id))


def simulate_days(sub_id: str, days: float) -> dict:
    """Demo only: move this subscription's clock forward to show the pre-charge reminder."""
    if not config.DEMO_MODE:
        raise orders.OrderError("disabled outside demo mode", 403)
    sub = get(sub_id)
    db.update("subscriptions", "id", sub_id, clock_offset=(sub["clock_offset"] or 0) + days * 86400, reminder_json=None)
    return view_sub(get(sub_id))


def record_use(sub_id: str) -> dict:
    """Seller records a delivery (e.g. this month's film rolls shipped), so reminders can be honest about value."""
    sub = get(sub_id)
    db.update("subscriptions", "id", sub_id, uses=(sub["uses"] or 0) + 1)
    ledger.append("subscription.delivery", {"subscription_id": sub_id, "uses": (sub["uses"] or 0) + 1},
                  seller_id=sub["seller_id"])
    return view_sub(get(sub_id))


REMINDER_SYSTEM = """You write the reminder a subscription service sends before a free trial turns into a paid charge.
Be radically honest: the goal is that nobody is charged for something they forgot or don't use.
Use ONLY the facts given. If the subscriber barely used it, say so and suggest cancelling.
Return JSON only: {"headline": "max 12 words", "body": "2-3 short sentences", "recommendation": "keep"|"cancel"|"either",
"why": "one sentence grounded in the usage numbers"}"""


def reminder(sub_id: str) -> dict:
    sub = get(sub_id)
    v = view_sub(sub)
    off = v["offering"]
    facts = {"product": off["name"], "sold_by": (off.get("seller") or {}).get("name", "TrustLayer"),
             "charge_amount_usd": sub["price"], "days_until_charge": v["days_until_charge"],
             "benefits": off["benefits"], "usage_during_trial": v["usage"]}
    try:
        res = llm.complete_json(REMINDER_SYSTEM, json.dumps(facts), temperature=0.2)
        d = res["data"] if isinstance(res["data"], dict) else {}
        rec = {"headline": d.get("headline", ""), "body": d.get("body", ""), "why": d.get("why", ""),
               "recommendation": d.get("recommendation") if d.get("recommendation") in ("keep", "cancel", "either") else "either",
               "model": res["model"]}
    except llm.LLMUnavailable:
        rec = {"headline": f"Your trial ends in {v['days_until_charge']:g} days",
               "body": "Cancel any time before then and you won't be charged.", "why": "", "recommendation": "either",
               "model": None}
    # The facts that matter are stated by code, not by the model.
    rec["fact"] = (f"You will be charged ${sub['price']:.2f} on "
                   f"{time.strftime('%b %d, %Y', time.localtime(sub['next_billing_at'] or time.time()))} unless you cancel.")
    db.update("subscriptions", "id", sub_id, reminder_json=json.dumps(rec))
    ledger.append("subscription.reminder", {"subscription_id": sub_id, "offering_id": off["id"],
                                            "recommendation": rec["recommendation"],
                                            "days_until_charge": v["days_until_charge"], "model": rec["model"]},
                  seller_id=sub["seller_id"])
    return view_sub(get(sub_id))


CANCEL_SYSTEM = """A subscriber is cancelling. Write one short, warm sentence confirming it is easy and immediate.
Only if usage shows they got real value, you may mention ONE alternative: pausing instead. Never argue, never
guilt-trip, never hide the cancel option.
Return JSON only: {"message": "max 30 words", "offer_pause": true|false}"""


def cancel_assist(sub_id: str) -> dict:
    v = view_sub(get(sub_id))
    try:
        res = llm.complete_json(CANCEL_SYSTEM, json.dumps({"usage": v["usage"]}), temperature=0.2)
        d = res["data"] if isinstance(res["data"], dict) else {}
        msg, offer = d.get("message") or "Cancelling takes one confirmation.", bool(d.get("offer_pause"))
    except llm.LLMUnavailable:
        msg, offer = "Cancelling takes one confirmation and is effective immediately.", False
    return {"message": msg, "offer_pause": offer and v["used"] and v["status"] == "ACTIVE"}  # code has the final say


def cancel(sub_id: str, reason: str) -> dict:
    sub = get(sub_id)
    if sub["status"] in ("CANCELLED", "EXPIRED"):
        return view_sub(sub)
    was_trial = view_sub(sub)["in_trial"]
    paypal.cancel_subscription(sub_id, reason or "Cancelled by subscriber in one confirmation")
    db.update("subscriptions", "id", sub_id, status="CANCELLED", cancel_reason=reason or None, cancelled_at=time.time())
    ledger.append("subscription.cancelled", {"subscription_id": sub_id, "reason": reason, "confirmations": 1,
                                             "cancelled_during_trial": was_trial}, seller_id=sub["seller_id"])
    return view_sub(get(sub_id))


def pause(sub_id: str) -> dict:
    paypal.suspend_subscription(sub_id, "Paused by subscriber")
    db.update("subscriptions", "id", sub_id, status="SUSPENDED")
    ledger.append("subscription.paused", {"subscription_id": sub_id}, seller_id=get(sub_id)["seller_id"])
    return view_sub(get(sub_id))


def resume(sub_id: str) -> dict:
    paypal.activate_subscription(sub_id)
    db.update("subscriptions", "id", sub_id, status="ACTIVE")
    ledger.append("subscription.resumed", {"subscription_id": sub_id}, seller_id=get(sub_id)["seller_id"])
    return view_sub(get(sub_id))


def seller_subscribers(seller_id: str) -> dict:
    subs = [view_sub(s) for s in db.all("SELECT * FROM subscriptions WHERE seller_id = ? ORDER BY created_at DESC",
                                        (seller_id,))]
    active = [s for s in subs if s["status"] in ("ACTIVE", "APPROVED")]
    return {"offerings": list_offerings(seller_id), "subscribers": subs,
            "summary": {"active": len(active), "in_trial": sum(s["in_trial"] for s in active),
                        "monthly_revenue": round(sum(s["price"] for s in active if not s["in_trial"]), 2),
                        "at_risk": sum(s["chargeback_risk"] for s in active)}}


def on_webhook(event_type: str, resource: dict) -> str | None:
    """Apply BILLING.SUBSCRIPTION.* / PAYMENT.SALE.COMPLETED to our record. Returns the subscription id if matched."""
    sub_id = resource.get("id") if event_type.startswith("BILLING.SUBSCRIPTION.") else resource.get("billing_agreement_id")
    if not sub_id or not db.one("SELECT 1 AS x FROM subscriptions WHERE id = ?", (sub_id,)):
        return None
    if event_type.startswith("BILLING.SUBSCRIPTION."):
        status = {"ACTIVATED": "ACTIVE", "CANCELLED": "CANCELLED", "SUSPENDED": "SUSPENDED",
                  "EXPIRED": "EXPIRED"}.get(event_type.rsplit(".", 1)[-1])
        if status:
            db.update("subscriptions", "id", sub_id, status=status)
    ledger.append("subscription.webhook", {"subscription_id": sub_id, "event_type": event_type},
                  seller_id=get(sub_id)["seller_id"])
    return sub_id
