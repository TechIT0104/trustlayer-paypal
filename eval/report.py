"""Turn eval/results/summary.json into NUMBERS.md and the README's evaluation section.

Usage: .venv/Scripts/python eval/report.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
S = json.loads((ROOT / "eval" / "results" / "summary.json").read_text())
PER = [json.loads(l) for l in (ROOT / "eval" / "results" / "per_example.jsonl").read_text().splitlines()]


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def row(name: str, m: dict) -> str:
    return (f"| {name} | {pct(m['recall'])} ({m['tp']}/{m['tp'] + m['fn']}) | {pct(m['precision'])} | "
            f"{pct(m['false_pause_rate'])} ({m['fp']}/{m['fp'] + m['tn']}) | {pct(m['honest_buyers_warned'])} | "
            f"{pct(m['scams_fully_missed'])} | {m['f1']:.2f} |")


table = "\n".join([
    "| Detector | Scams paused (recall) | Precision | Honest buyers wrongly paused | Honest buyers shown any warning | Scams with no warning at all | F1 |",
    "|---|---|---|---|---|---|---|",
    row("Rules only", S["rules"]), row("LLM only (grounded)", S["llm"]), row("**TrustLayer (fused)**", S["fused"]),
])

misses = [p for p in PER if (p["fused"] == "PAUSE") != (p["label"] == "scam")]
miss_lines = "\n".join(f"- `{p['id']}` {p['label']} / {p['type']}: fused={p['fused']} (rules={p['rules']}, llm={p['llm']}, "
                       f"ai_type={p['ai_type']}, rule signals={', '.join(p['rule_keys']) or 'none'})" for p in misses) or "- none"
per_type = "\n".join(f"| {t} | {v} |" for t, v in S["per_type_fused_recall_or_specificity"].items())
lat = S["llm_latency_ms"]

short = f"""**{S['n']} labelled marketplace chats** ({S['n_scam']} scams across 10 tactics, {S['n_legit']} honest chats including
deliberate traps such as sellers warning *against* Friends & Family). Classifier: `{S['classifier_model']}`.

{table}

- Scam **tactic named correctly** on {pct(S['tactic_accuracy_on_scams'])} of scams · LLM latency p50 {lat['p50']} ms, p95 {lat['p95']} ms
- **{S['ungrounded_quotes_dropped']} AI-cited quotes were not in the chat** and were discarded by the grounding check
- Full breakdown, every miss, and method: [NUMBERS.md](NUMBERS.md)"""

numbers = f"""# NUMBERS: Pay-pause evaluation

Measured, not claimed. Re-run with `python eval/run_eval.py` then `python eval/report.py`.

## Setup
- Dataset: `{S['dataset']}`, {S['n']} chats ({S['n_scam']} scam / {S['n_legit']} legit), generated by
  `qwen/qwen3.8-27b` from 20 scenario specs (`eval/generate_dataset.py`). Labels come from the scenario, never from a classifier.
  The generator is a different model from the classifier to limit self-grading bias.
- Classifier: `{S['classifier_model']}` on Groq, temperature 0, one provider only (no fallback) for a clean measurement.
- Positive class = scam. An intervention is a **PAUSE** (money held + cooling-off). CAUTION shows a warning but does not hold money.

## Results
{table}

Tactic accuracy on scams: **{pct(S['tactic_accuracy_on_scams'])}**. Ungrounded AI quotes discarded: **{S['ungrounded_quotes_dropped']}**.
LLM latency: p50 **{lat['p50']} ms**, p95 **{lat['p95']} ms**.

### Per scenario (fused: scams paused / honest not paused)
| Scenario | Correct |
|---|---|
{per_type}

### Every fused error
{miss_lines}

## Caveats
- Generated chats are realistic but not real; they measure behaviour on known patterns, not real-world prevalence.
- 100 examples gives wide confidence intervals (about ±10 points on each rate).
- Rules and prompts were written before this dataset was generated; nothing was tuned on it afterwards.
"""
(ROOT / "NUMBERS.md").write_text(numbers, encoding="utf-8")
readme = (ROOT / "README.md").read_text(encoding="utf-8")
readme = re.sub(r"<!-- EVAL:START -->.*<!-- EVAL:END -->", f"<!-- EVAL:START -->\n{short}\n<!-- EVAL:END -->", readme, flags=re.S)
(ROOT / "README.md").write_text(readme, encoding="utf-8")
print(short)
